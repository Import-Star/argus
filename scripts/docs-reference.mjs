// Writes docs/settings.md and docs/commands.md from package.json, so the docs site lists every setting and
// command. Run `npm run docs:reference` after changing contributes.configuration or contributes.commands.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const pkg = JSON.parse(readFileSync(path.join(root, "package.json"), "utf8"));
const cell = (text) => String(text).replace(/\|/g, "\|").replace(/\s*\n\s*/g, " ");
const code = (value) => `\`${JSON.stringify(value)}\``;

const GROUPS = [
  ["argus.sessions.", "Sessions board"],
  ["argus.notifications", "Notifications"],
  ["argus.prs.", "Pull requests"],
  ["argus.chat.", "Chat"],
  ["argus.diffReview.", "Diff review"],
  ["argus.usage.", "Plan usage"],
  ["argus.keepAwake.", "Keep awake"],
  ["argus.plugins.", "Plugins"],
  ["argus.whatsNew.", "What's New"]
];

const properties = Object.assign({}, ...[pkg.contributes.configuration].flat().map((group) => group.properties));
const sections = GROUPS.map(([prefix, title]) => {
  const rows = Object.entries(properties)
    .filter(([key]) => key.startsWith(prefix))
    .map(([key, spec]) => {
      const description = spec.deprecationMessage ? `**Deprecated.** ${spec.deprecationMessage}` : (spec.markdownDescription ?? spec.description ?? "");
      const notes = spec.markdownEnumDescriptions ?? spec.enumDescriptions;
      const values = spec.enum
        ? `<br>${spec.enum.map((value, at) => `\`${value}\`${notes?.[at] ? `: ${cell(notes[at])}` : ""}`).join("<br>")}`
        : "";
      return `| \`${key}\` | ${code(spec.default)} | ${cell(description)}${values} |`;
    });
  return rows.length ? `## ${title}\n\n| Setting | Default | Description |\n| --- | --- | --- |\n${rows.join("\n")}\n` : "";
}).filter(Boolean);

const listed = new Set(GROUPS.flatMap(([prefix]) => Object.keys(properties).filter((key) => key.startsWith(prefix))));
const missed = Object.keys(properties).filter((key) => !listed.has(key));
if (missed.length) {
  throw new Error(`Settings with no docs group in scripts/docs-reference.mjs: ${missed.join(", ")}`);
}

writeFileSync(
  path.join(root, "docs", "settings.md"),
  `---
title: Settings
nav_order: 5
---

<!-- Generated by scripts/docs-reference.mjs from package.json. Don't edit by hand. -->

# Settings

Every Argus setting, as it appears in VS Code's Settings and on the Control Center's
[Settings tab](features/control-center.md#settings-tab). Settings work at user or workspace level.

${sections.join("\n")}`
);

const palette = pkg.contributes.commands.filter((command) => command.title.startsWith("Argus:"));
const view = pkg.contributes.commands.filter((command) => !command.title.startsWith("Argus:"));
const commandRows = (list) => list.map((command) => `| **${command.title}** | \`${command.command}\` |`).join("\n");
writeFileSync(
  path.join(root, "docs", "commands.md"),
  `---
title: Commands
nav_order: 6
---

<!-- Generated by scripts/docs-reference.mjs from package.json. Don't edit by hand. -->

# Commands

## Command palette

| Command | ID |
| --- | --- |
${commandRows(palette)}

**Argus: Open Chats Side by Side** shows only while \`argus.chat.experimentalMultiAgent\` is on.

## Sessions view

On the Sessions view's toolbar, its cards' icons and their context menu.

| Command | ID |
| --- | --- |
${commandRows(view)}

Plugins add their own commands; **Argus: Run Plugin Command** lists them.
`
);
console.log(`docs/settings.md: ${Object.keys(properties).length} settings; docs/commands.md: ${pkg.contributes.commands.length} commands`);
